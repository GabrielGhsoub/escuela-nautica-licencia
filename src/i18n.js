const KEY = 'env-lic-lang'
const saved = (() => { try { return localStorage.getItem(KEY) } catch { return null } })()

const LangContext = createContext({
  lang: 'es',
  setLang: () => {},
  t: (key) => messages.es[key] ?? key,
})

export function LangProvider({ children }) {
  const [lang, setLang] = useState(saved === 'en' ? 'en' : 'es')

  useEffect(() => {
    document.documentElement.lang = lang
    document.title = messages[lang]['doc.title']
  }, [lang])

  const value = useMemo(() => ({
    lang,
    setLang: (next) => {
      const l = next === 'en' ? 'en' : 'es'
      try { localStorage.setItem(KEY, l) } catch { /* private mode */ }
      setLang(l)
    },
    t: (key) => {
      const hit = messages[lang][key] ?? messages.es[key]
      return hit === undefined ? key : hit
    },
  }), [lang])

  return createElement(LangContext.Provider, { value }, children)
}

export function useLang() {
  return useContext(LangContext)
}
